// Keeps representations of schema/flow.v1.schema.json in sync:
//   - src/schema.generated.ts   (TS module, importable in browsers where fs is unavailable)
//   - ../../go/flow/flow.v1.schema.json  (embedded by the Go package)
// Usage: node scripts/sync-schema.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const src = here("../schema/flow.v1.schema.json");
const raw = readFileSync(src, "utf8");
const json = JSON.parse(raw);

const ts =
  "// SPDX-License-Identifier: Apache-2.0\n" +
  "// GENERATED by scripts/sync-schema.mjs from schema/flow.v1.schema.json. Do not edit.\n" +
  "// eslint-disable-next-line @typescript-eslint/no-explicit-any\n" +
  "export const flowSchema: Record<string, any> = " + JSON.stringify(json, null, 2) + ";\n";

const targets = [
  [here("../src/schema.generated.ts"), ts],
  [here("../../../go/flow/flow.v1.schema.json"), raw],
];

const check = process.argv.includes("--check");
let stale = false;
for (const [path, want] of targets) {
  let have = null;
  try { have = readFileSync(path, "utf8"); } catch { /* missing */ }
  if (have === want) continue;
  if (check) { console.error(`stale: ${path}`); stale = true; } else { writeFileSync(path, want); console.log(`wrote ${path}`); }
}
process.exit(stale ? 1 : 0);
