// Regenerates src/schema.generated.ts from the control-plane OpenAPI document.
// Usage: node scripts/gen-types.mjs [--check]   (--check fails if the committed file is stale)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const spec = new URL("../../../../core/control-plane/openapi.yaml", import.meta.url);
const out = fileURLToPath(new URL("../src/schema.generated.ts", import.meta.url));
const header =
  "// SPDX-License-Identifier: Apache-2.0\n// GENERATED by scripts/gen-types.mjs from core/control-plane/openapi.yaml. Do not edit.\n\n";
const ast = await openapiTS(spec);
const text = header + astToString(ast).replace(/\r\n/g, "\n");
if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (cur !== text) {
    console.error("schema.generated.ts is stale: run `pnpm --filter @nurtuo/client gen`");
    process.exit(1);
  }
  console.log("schema.generated.ts is up to date");
} else {
  writeFileSync(out, text);
  console.log("wrote", out);
}
