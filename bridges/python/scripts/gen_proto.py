"""Generate the Python stubs for nurtuo.connector.v1 into src/nurtuo_bridge/_gen.

Usage (from bridges/python):  python scripts/gen_proto.py [--check]

Needs ``grpcio-tools`` (``pip install -e .[dev]``). The generated code is committed so that
installing the bridge does not need a protobuf compiler; ``--check`` regenerates into a temp
directory and fails if the committed files are stale (use it in CI).
"""

from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROTO_ROOT = ROOT.parents[1] / "proto"
PROTO_FILE = "nurtuo/connector/v1/connector.proto"
GEN_PACKAGE = "nurtuo_bridge._gen"
GEN_DIR = ROOT / "src" / "nurtuo_bridge" / "_gen"
HEADER = "# SPDX-License-Identifier: Apache-2.0\n# Code generated by scripts/gen_proto.py from {proto}. DO NOT EDIT.\n"


def generate(out: Path) -> None:
    import grpc_tools
    from grpc_tools import protoc

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    well_known = Path(grpc_tools.__file__).parent / "_proto"
    rc = protoc.main(
        [
            "grpc_tools.protoc",
            f"-I{PROTO_ROOT}",
            f"-I{well_known}",
            f"--python_out={out}",
            f"--pyi_out={out}",
            f"--grpc_python_out={out}",
            str(PROTO_ROOT / PROTO_FILE),
        ]
    )
    if rc != 0:
        sys.exit(f"protoc failed with exit code {rc}")
    pkg_re = re.compile(r"^from nurtuo\.connector\.v1 import (\w+)", re.MULTILINE)
    for f in out.rglob("*.py*"):
        text = f.read_text(encoding="utf-8")
        text = pkg_re.sub(rf"from {GEN_PACKAGE}.nurtuo.connector.v1 import \1", text)
        if f.suffix == ".py":
            text = HEADER.format(proto=PROTO_FILE) + text
        f.write_text(text, encoding="utf-8", newline="\n")
    for d in [out, *[p for p in out.rglob("*") if p.is_dir()]]:
        init = d / "__init__.py"
        if not init.exists():
            init.write_text("# SPDX-License-Identifier: Apache-2.0\n", encoding="utf-8", newline="\n")


def same(a: Path, b: Path) -> bool:
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.diff_files:
        return False
    return all(same(a / d, b / d) for d in cmp.common_dirs)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if committed stubs are stale")
    args = ap.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / "_gen"
            generate(fresh)
            if not GEN_DIR.exists() or not same(fresh, GEN_DIR):
                sys.exit("generated stubs are stale: run `python scripts/gen_proto.py`")
        print("generated stubs are up to date")
        return
    generate(GEN_DIR)
    print(f"generated {GEN_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
