func init() {
	register("standalone", func(args []string, _, _ io.Writer) int { return runStandalone(args) })
}

// defaultControlPlaneEntry is the control plane script path relative to the repo/install root.
var defaultControlPlaneEntry = filepath.Join("core", "control-plane", "dist", "main.js")

// resolveControlPlaneEntry turns the --control-plane-entry value into a usable path. Absolute
// paths and the empty string pass through. A relative path is searched, in order, in the
// executable's directory and its ancestors, then in the working directory and its ancestors;
// the first existing match wins. If nothing exists the original value is returned so the
// child fails with a clear "file not found" message.
func resolveControlPlaneEntry(entry, exeDir, cwd string) string {
	if entry == "" || filepath.IsAbs(entry) {
		return entry
	}
	for _, start := range []string{exeDir, cwd} {
		for dir := start; dir != ""; {
			cand := filepath.Join(dir, entry)
			if _, err := os.Stat(cand); err == nil {
				return cand
			}
			parent := filepath.Dir(dir)
			if parent == dir {
				break
			}
			dir = parent
		}
	}
	return entry
}

func executableDir() string {
	exe, err := os.Executable()
	if err != nil {
		return ""
	}
	return filepath.Dir(exe)
}

func mustGetwd() string {
	wd, _ := os.Getwd()
	return wd
}

// runRealRuntime runs internal/runtime.Run against the local control plane gateway using the
// client certificate generated by the standalone bootstrapper.
func runRealRuntime(gatewayAddr string) RuntimeFunc {
	return func(ctx context.Context, env RuntimeEnv) error {
		return nrt.Run(ctx, nrt.Config{
			RuntimeID:       "standalone",
			ControlPlaneURL: gatewayAddr,
			CertFile:        env.Creds.ClientCertFile,
			KeyFile:         env.Creds.ClientKeyFile,
			CAFile:          env.Creds.CAFile,
			ServerName:      "localhost",
			// User secrets of bundle connections live in an encrypted store beside the bootstrap secrets.
			Secrets: secrets.Config{Provider: secrets.ProviderEncryptedFile, Path: filepath.Join(env.Dirs.Secrets, "store")},
		})
	}
}
