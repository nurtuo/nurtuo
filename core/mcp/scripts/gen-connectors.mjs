// Generates src/connectors.generated.ts from connectors/*/connector.yaml (the Apache-2.0 native
// connector descriptors), inlining `$ref: schemas/...` connection schemas. Runs as part of `build`;
// `--check` fails if the committed file is stale (also asserted by a unit test).
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..", "connectors");
const out = join(here, "..", "src", "connectors.generated.ts");

const entries = [];
for (const dir of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const file = join(root, dir, "connector.yaml");
  if (!existsSync(file)) continue;
  const y = parse(readFileSync(file, "utf8"));
  let connectionSchema = null;
  const schemaRef = y.connection?.schema?.$ref;
  if (schemaRef) connectionSchema = JSON.parse(readFileSync(join(root, dir, schemaRef), "utf8"));
  entries.push({
    id: y.id,
    version: y.version,
    displayName: y.displayName,
    description: y.description ?? "",
    host: y.host,
    operations: (y.operations ?? []).map((o) => ({
      type: o.type,
      ...(o.customType ? { customType: o.customType } : {}),
      /** Value to put in a connector step's `config.operation`. */
      operation: o.customType ?? o.type,
      ...(o.supportsBrowse ? { supportsBrowse: true } : {}),
      description: o.description ?? "",
    })),
    connectionFields: y.connection?.fields ?? (connectionSchema ? Object.keys(connectionSchema.properties ?? {}) : []),
    connectionSchema,
    options: y.options ?? [],
    trackedProperties: y.trackedProperties ?? [],
    capabilities: y.capabilities ?? {},
  });
}

const text =
  "// SPDX-License-Identifier: AGPL-3.0-only\n" +
  "// GENERATED by scripts/gen-connectors.mjs from connectors/*/connector.yaml. Do not edit.\n" +
  "export interface ConnectorOperationInfo {\n" +
  "  type: string; customType?: string; operation: string; supportsBrowse?: boolean; description: string;\n" +
  "}\n" +
  "export interface ConnectorInfo {\n" +
  "  id: string; version: string; displayName: string; description: string; host: string;\n" +
  "  operations: ConnectorOperationInfo[];\n" +
  "  connectionFields: string[];\n" +
  "  connectionSchema: Record<string, unknown> | null;\n" +
  "  options: string[]; trackedProperties: string[]; capabilities: Record<string, unknown>;\n" +
  "}\n" +
  `export const CONNECTORS: ConnectorInfo[] = ${JSON.stringify(entries, null, 2)};\n`;

if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (cur !== text) {
    console.error("connectors.generated.ts is stale; run `pnpm --filter @nurtuo/mcp run sync`");
    process.exit(1);
  }
  console.log("connectors.generated.ts up to date");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${entries.length} connectors to src/connectors.generated.ts`);
}
